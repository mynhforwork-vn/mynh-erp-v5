import assert from 'node:assert/strict'
import fs from 'node:fs'
import {userAuditChange} from '../lib/user-audit-history.ts'
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8')
const field=(action,key,a,b)=>userAuditChange({action,old_value:{[key]:a},new_value:{[key]:b}})
assert.deepEqual(field('UPDATE_DEVICE','device','iPhone 12','iPhone 15'),{label:'Thiết bị',before:'iPhone 12',after:'iPhone 15'})
assert.deepEqual(field('UPDATE_EMAIL','email','a@example.test','b@example.test'),{label:'Email',before:'a@example.test',after:'b@example.test'})
assert.deepEqual(field('UPDATE_PHONE','phone','0995733165','0995733166'),{label:'Số điện thoại',before:'0995 733 165',after:'0995 733 166'})
assert.equal(userAuditChange({action:'UPDATE_DEVICE',old_value:null,new_value:{device:'B'}}),null,'do not fabricate missing old value')
assert.equal(userAuditChange({action:'UPDATE_SPC_ST',old_value:{spc:'X'},new_value:{spc:'Y'}}),null,'never reveal SPC in history')
const sql=read('supabase/migrations/0073_user_device_history_spc_secure_copy.sql')
assert.match(sql,/FROM vault\.decrypted_secrets/,'read only from Vault')
assert.match(sql,/current_erp_role\(\) NOT IN \('admin','operator'\)/,'RPC RBAC')
assert.match(sql,/REVOKE ALL ON FUNCTION public\.get_erp_user_spc_for_copy/,'no public RPC execution')
assert.match(sql,/COPY_SPC_ST/,'copy audit event')
assert.match(sql,/v_before IS DISTINCT FROM v_after/,'ignore unchanged device')
assert.doesNotMatch(sql,/jsonb_build_object\([^)]*(?:spc_st|spc_f)/i,'never audit SPC values')
const api=read('app/api/users/spc/copy/route.ts')
assert.match(api,/new URL\(origin as string\).host===new URL\(req.url\).host/,'cross-origin denied')
assert.match(api,/if\(!sameOrigin\)/,'missing or malformed origin denied')
assert.match(api,/no-store/,'no caching')
assert.match(api,/supabase\.auth\.getUser\(\)/,'live auth')
const component=read('components/spc-copy-control.tsx')
assert.match(component,/navigator\.clipboard\.writeText/,'copy on demand only')
assert.doesNotMatch(component,/(?:localStorage|sessionStorage|console\.log|setInterval)/,'never store secret in client')
const page=read('app/(erp)/users/page.tsx')
assert.match(page,/const diff=userAuditChange\(h\)/,'history renders old/new')
assert.match(page,/canOperate&&<SpcCopyControl/,'copy shown only to operator')
assert.doesNotMatch(page,/<textarea name="spc_(?:st|f)"/,'SPC fields must not show plaintext as textareas')
assert.match(page,/<input type="password" name="spc_st"/,'SPC ST entry is masked')
assert.match(page,/<input type="password" name="spc_f"/,'SPC F entry is masked')
assert.match(component,/setTimeout\(\(\)=>setFeedback\(''\),5000\)/,'copy feedback clears after five seconds')

const compactCss=read('app/styles/user-history-spc-copy.css')
assert.match(component,/<svg className="spc-copy-icon"/,'SPC button has copy icon')
assert.match(component,/aria-hidden="true"/,'copy SVG is decorative')
assert.match(component,/aria-label=\{/,'icon button remains accessible')
assert.match(component,/title=\{/,'icon has tooltip')
assert.doesNotMatch(component,/\{busy\?'Đang sao chép…':'Sao chép '\+kind\}/,'no text occupying button width')
assert.match(compactCss,/width:26px;height:26px/,'SPC icon button is compact')
assert.match(compactCss,/\.spc-copy-feedback\{position:absolute/,'feedback does not expand slidebar row')
assert.match(page,/className="spc-value-inline"/,'SPC copy is inline in details')
assert.match(page,/className="secret-state spc-secret-inline"/,'SPC copy stays inline in edit form')
assert.doesNotMatch(page,/className="spc-copy-actions"/,'remove separate copy action row')
console.log('PASS USER_HISTORY_SPC_STATIC_QA (no SQL DB E2E; migration staged)')
