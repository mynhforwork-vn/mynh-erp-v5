import assert from 'node:assert/strict'
import {sample} from './fixtures/shopee-pending-payment-sample.mjs'
import {parseShopeeOrderText,formatParsedOrderSummary} from '../lib/shopee-order-text-parser.ts'
let passed=0
const check=(name,actual,expected)=>{assert.deepEqual(actual,expected,name);passed++}
for(const [kind,input] of [['plain',sample],['trailing-backslashes',sample.replaceAll('\n','\\\n')]]){
  const p=parseShopeeOrderText(input)
  check(kind+' order',p.shopee_order_id,'261013TESTQA01')
  check(kind+' Shopee review',p.detected_status,'PENDING_SHOPEE_CONFIRMATION')
  check(kind+' absent order date',p.order_date_local,undefined)
  check(kind+' no tracking',p.tracking_number,undefined)
  check(kind+' recipient',p.recipient_name,'Nguyễn Thị Mẫu')
  check(kind+' normalized phone',p.recipient_phone,'0900123456')
  check(kind+' exact address without seller',p.recipient_address,'Số 10, Đường Mẫu, Phường Cửa Nam, Thành phố Hà Nội')
  check(kind+' recipient confidence',p.confidence.recipient,true)
  check(kind+' two products',p.products.length,2)
  check(kind+' first product',p.products[0].product_name,'Combo 1-3-5 Thanh KitKat Milo Nestle 16g ( Xanh )')
  check(kind+' first variant',p.products[0].variant,'1 Thanh')
  check(kind+' second product',p.products[1].product_name,'Chai Dầu ăn Simply đậu nành/Dầu gạo 1 Lít')
  check(kind+' second variant',p.products[1].variant,'Đậu Nành 1 Lít,1 Chai')
  check(kind+' item quantities',p.products.map(x=>x.quantity),[1,1])
  check(kind+' item original prices',p.products.map(x=>x.original_price),[19800,80700])
  check(kind+' no made-up sale price',p.products.map(x=>x.final_price),[null,null])
  check(kind+' goods total',p.total_goods,100500)
  check(kind+' shipping fee',p.shipping_fee,1000)
  check(kind+' shipping voucher discount',p.shipping_discount,1000)
  check(kind+' Shopee voucher discount',p.shopee_voucher_discount,100000)
  check(kind+' final payable',p.cod,500)
  check(kind+' payment method',p.payment_method,'COD')
  check(kind+' payment not yet made',p.payment_status,'UNPAID')
  check(kind+' vouchers',p.vouchers.map(v=>[v.voucher_type,v.voucher_tag]),[['Vận chuyển','Phí vận chuyển'],['Shopee','Shopee']])
  check(kind+' no invented voucher codes',p.vouchers.every(v=>!v.voucher_code),true)
  check(kind+' balanced totals',p.warnings,[])
  check(kind+' readable summary',formatParsedOrderSummary(p).includes('Shopee đang xét duyệt'),true)
}
const generic=parseShopeeOrderText('Chờ thanh toán\nPhương thức Thanh toán\nCash on Delivery')
check('generic unpaid not system review',generic.detected_status,undefined)
check('COD alone is unpaid',generic.payment_status,'UNPAID')
const wrong=parseShopeeOrderText(sample.replace('-100.000₫','-90.000₫'))
check('mismatching discount yields warning',wrong.warnings.length,1)
check('never alter copied COD to force balance',wrong.cod,500)
const existing=parseShopeeOrderText('Đang vận chuyển\nMÃ ĐƠN HÀNG. 261013TESTQA02\nSPXVN123456789')
check('shipping status regression',existing.detected_status,'IN_TRANSIT')
check('tracking regression',existing.tracking_number,'SPXVN123456789')
console.log('SHOPEE_PENDING_QA_SUMMARY '+JSON.stringify({passed,failed:0}))
